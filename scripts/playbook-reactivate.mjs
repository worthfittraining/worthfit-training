async function airtableFetch(url, options = {}) {
  const res = await fetch(url, {
    ...options,
    headers: {
      Authorization: `Bearer ${TOKEN}`,
      'Content-Type': 'application/json',
      ...(options.headers || {}),
    },
  })
  if (!res.ok) {
    const text = await res.text()
    throw new Error(`Airtable error ${res.status}: ${text}`)
  }
  return res.json()
}

async function fetchAllRecords() {
  const records = []
  let offset = null
  do {
    const params = new URLSearchParams({ pageSize: '100' })
    params.append('fields[]', 'Email')
    params.append('fields[]', 'Playbook_Active')
    params.append('fields[]', 'Plan')
    if (offset) params.set('offset', offset)
    const data = await airtableFetch(
      `https://api.airtable.com/v0/${BASE_ID}/${encodeURIComponent(TABLE)}?${params}`
    )
    records.push(...(data.records || []))
    offset = data.offset || null
    process.stdout.write(`\r  Fetched ${records.length} records...`)
  } while (offset)
  console.log()
  return records
}

async function batchUpdate(records, fields) {
  const chunks = []
  for (let i = 0; i < records.length; i += 10) chunks.push(records.slice(i, i + 10))
  let updated = 0
  for (const chunk of chunks) {
    await airtableFetch(
      `https://api.airtable.com/v0/${BASE_ID}/${encodeURIComponent(TABLE)}`,
      {
        method: 'PATCH',
        body: JSON.stringify({
          records: chunk.map(r => ({ id: r.id, fields })),
        }),
      }
    )
    updated += chunk.length
    process.stdout.write(`\r  Updated ${updated} / ${records.length}`)
  }
  console.log()
}

async function main() {
  console.log('=== Playbook Reactivate — 1031 active subscribers ===')
  console.log('Fetching all Airtable records...')
  const all = await fetchAllRecords()
  console.log(`Total Airtable records: ${all.length}`)

  const toActivate = []
  const toDeactivate = []

  for (const r of all) {
    const email = (r.fields?.Email || '').toLowerCase().trim()
    const isActive = ACTIVE_EMAILS.has(email)
    const currentlyActive = !!r.fields?.Playbook_Active
    const currentPlan = r.fields?.Plan || 'free'

    if (isActive && (!currentlyActive || currentPlan !== 'standard')) {
      toActivate.push(r)
    } else if (!isActive && currentlyActive) {
      toDeactivate.push(r)
    }
  }

  console.log(`${toActivate.length} records to activate (Playbook_Active=true, Plan=standard)`)
  console.log(`${toDeactivate.length} records to deactivate (Playbook_Active=false)`)

  if (toActivate.length > 0) {
    console.log('Activating...')
    await batchUpdate(toActivate, { Playbook_Active: true, Plan: 'standard' })
  }

  if (toDeactivate.length > 0) {
    console.log('Deactivating inactive members...')
    await batchUpdate(toDeactivate, { Playbook_Active: false })
  }

  console.log('\nDone!')
  console.log(`  ✅ ${toActivate.length} active subscribers set to Playbook_Active=true, Plan=standard`)
  console.log(`  ✅ ${toDeactivate.length} inactive members set to Playbook_Active=false`)
}

main().catch(err => {
  console.error('Error:', err.message)
  process.exit(1)
})
